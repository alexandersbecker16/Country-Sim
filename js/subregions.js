/**
 * Fine-grained worldwide tech/industry subregions.
 * Checked BEFORE country-wide profiles — first matching box wins.
 * Compact factory keeps the list readable; scores are 0–100.
 */
function SR(name, lon0, lon1, lat0, lat1, o) {
  const tech = o.t;
  return {
    name,
    subregion: true,
    lon: [lon0, lon1],
    lat: [lat0, lat1],
    tech,
    industry: o.i ?? Math.max(20, tech - 6),
    naval: o.n ?? 30,
    airforce: o.a ?? 35,
    nuclear: o.u ?? 0,
    weaponized: o.w ?? Math.round(tech * 0.45),
    weaponizable: o.d ?? Math.round(tech * 0.7),
    militarism: o.m ?? 45,
    pacifism: o.p ?? 40,
    island: !!o.island,
    weapons: o.weapons || [],
    dualUse: o.dualUse || [],
    hub: o.hub !== false && tech >= 78, // high-tech hubs stack when owned together
    base: !!o.base, // military / strategic base — preferred nuke target
    nukeDef: o.nd ?? 0, // local missile / ABM defense 0–100
  };
}

